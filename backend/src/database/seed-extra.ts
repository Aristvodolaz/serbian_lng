/** Extra A1 lessons/words. Shape matches seed.ts UnitSeed — imported and merged there. */

export interface ChoiceSeed {
  text: string;
  isCorrect: boolean;
}
export interface ExerciseSeed {
  promptCyrillic: string;
  promptLatin: string;
  choices: ChoiceSeed[];
}
export interface LessonSeed {
  title: string;
  titleLatin: string;
  titleTranslation: string;
  exercises: ExerciseSeed[];
}
export interface WordSeed {
  cyrillic: string;
  latin: string;
  translation: string;
  exampleCyrillic: string;
  exampleTranslation: string;
}
export interface UnitSeed {
  titleCyrillic: string;
  titleLatin: string;
  titleTranslation: string;
  lessons: LessonSeed[];
  words: WordSeed[];
}

function ex(cyr: string, lat: string, correct: string, w1: string, w2: string): ExerciseSeed {
  return {
    promptCyrillic: cyr,
    promptLatin: lat,
    choices: [
      { text: correct, isCorrect: true },
      { text: w1, isCorrect: false },
      { text: w2, isCorrect: false },
    ],
  };
}

function wd(cyr: string, lat: string, translation: string, exampleCyrillic: string, exampleTranslation: string): WordSeed {
  return { cyrillic: cyr, latin: lat, translation, exampleCyrillic, exampleTranslation };
}

function lesson(title: string, titleLatin: string, titleTranslation: string, exercises: ExerciseSeed[]): LessonSeed {
  return { title, titleLatin, titleTranslation, exercises };
}

